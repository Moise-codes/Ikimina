"""Identifier generation.

Primary keys are UUIDs generated by the application. We use **UUIDv7** (RFC
9562): the first 48 bits are a millisecond timestamp, so values sort by
creation time. That keeps B-tree indexes healthy (new rows append near the end
of the index instead of scattering like v4) while remaining globally unique and
non-guessable.
"""

from __future__ import annotations

import secrets
import time
import uuid

_MILLIS_MASK = (1 << 48) - 1
_VERSION_7 = 0x7
_VARIANT_RFC = 0b10


def uuid7() -> uuid.UUID:
    """Return a time-ordered UUIDv7."""
    unix_ts_ms = int(time.time() * 1000) & _MILLIS_MASK
    rand_a = secrets.randbits(12)
    rand_b = secrets.randbits(62)
    value = (unix_ts_ms << 80) | (_VERSION_7 << 76) | (rand_a << 64) | (_VARIANT_RFC << 62) | rand_b
    return uuid.UUID(int=value)
